CREATE TABLE CUSTOMERS (
  CUSTOMER_ID INTEGER GENERATED BY DEFAULT AS IDENTITY,
  CODE        D_CODE,
  NAME        D_NAME,
  EMAIL       VARCHAR(120),
  BIRTH_DATE  D_BIRTHDATE,
  IS_ACTIVE   D_FLAG,
  CREATED_AT  D_CREATED,
  CONSTRAINT PK_CUSTOMERS      PRIMARY KEY (CUSTOMER_ID),
  CONSTRAINT UQ_CUSTOMERS_CODE UNIQUE (CODE),
  CONSTRAINT UQ_CUSTOMERS_MAIL UNIQUE (EMAIL)
);

CREATE TABLE PRODUCTS (
  PRODUCT_ID     INTEGER GENERATED ALWAYS AS IDENTITY,
  SKU            D_CODE NOT NULL,
  NAME           D_NAME,
  UNIT_PRICE     D_AMOUNT,
  TAX_RATE       NUMERIC(5,2) DEFAULT 23 NOT NULL,
  PRICE_WITH_TAX COMPUTED BY (UNIT_PRICE * (1 + TAX_RATE / 100)),
  CONSTRAINT PK_PRODUCTS     PRIMARY KEY (PRODUCT_ID),
  CONSTRAINT UQ_PRODUCTS_SKU UNIQUE (SKU)
);

CREATE TABLE ORDERS (
  ORDER_ID     INTEGER NOT NULL,
  CUSTOMER_ID  INTEGER NOT NULL,
  ORDER_DATE   D_CREATED,
  STATUS       D_CODE DEFAULT 'NEW',
  TOTAL_AMOUNT D_AMOUNT,
  CONSTRAINT PK_ORDERS       PRIMARY KEY (ORDER_ID),
  CONSTRAINT FK_ORDERS_CUST  FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS (CUSTOMER_ID)
);

CREATE TABLE ORDER_ITEMS (
  ORDER_ID   INTEGER NOT NULL,
  LINE_NO    INTEGER NOT NULL,
  PRODUCT_ID INTEGER NOT NULL,
  QTY        D_QTY,
  UNIT_PRICE D_AMOUNT,
  LINE_TOTAL COMPUTED BY (QTY * UNIT_PRICE),
  CONSTRAINT PK_ORDER_ITEMS  PRIMARY KEY (ORDER_ID, LINE_NO),
  CONSTRAINT FK_ITEMS_ORDER  FOREIGN KEY (ORDER_ID)   REFERENCES ORDERS (ORDER_ID),
  CONSTRAINT FK_ITEMS_PROD   FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS (PRODUCT_ID)
);

CREATE TABLE AUDIT_LOG (
  LOG_ID    INTEGER GENERATED BY DEFAULT AS IDENTITY,
  ENTITY    VARCHAR(30) NOT NULL,
  ENTITY_ID INTEGER,
  ACTION    VARCHAR(20),
  DETAILS   D_NOTES,
  LOGGED_AT D_CREATED,
  CONSTRAINT PK_AUDIT_LOG PRIMARY KEY (LOG_ID)
);

