CREATE FUNCTION FN_ADD_TAX(AMOUNT NUMERIC(15,2), RATE NUMERIC(5,2))
RETURNS NUMERIC(15,2)
AS
BEGIN
  RETURN AMOUNT * (1 + RATE / 100);
END^

CREATE FUNCTION FN_FULL_LABEL(CODE VARCHAR(8), NAME VARCHAR(60))
RETURNS VARCHAR(80)
AS
  DECLARE VARIABLE RESULT VARCHAR(80);
BEGIN
  IF (CODE IS NULL) THEN
    RESULT = NAME;
  ELSE
    RESULT = TRIM(CODE) || ' - ' || NAME;
  RETURN RESULT;
END^

