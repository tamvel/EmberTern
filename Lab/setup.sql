/* ---------- Domains -------------------------------------------------
   Cover: VARCHAR, CHAR, INTEGER, NUMERIC, DATE, TIMESTAMP, BLOB,
          DEFAULT, CHECK, NOT NULL.                                   */

CREATE DOMAIN D_NAME      AS VARCHAR(60) NOT NULL;
CREATE DOMAIN D_CODE      AS CHAR(8);
CREATE DOMAIN D_AMOUNT    AS NUMERIC(15,2) DEFAULT 0 NOT NULL CHECK (VALUE >= 0);
CREATE DOMAIN D_QTY       AS INTEGER DEFAULT 1 CHECK (VALUE > 0);
CREATE DOMAIN D_CREATED   AS TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL;
CREATE DOMAIN D_BIRTHDATE AS DATE;
CREATE DOMAIN D_FLAG      AS CHAR(1) DEFAULT 'N' CHECK (VALUE IN ('Y','N'));
CREATE DOMAIN D_NOTES     AS BLOB SUB_TYPE TEXT;

/* ---------- Generators / sequences ---------------------------------
   Cover: standard, START WITH, START WITH + INCREMENT BY.            */

CREATE SEQUENCE GEN_CUSTOMER_ID;
CREATE SEQUENCE GEN_ORDER_ID   START WITH 1000;
CREATE SEQUENCE GEN_INVOICE_NO START WITH 5000 INCREMENT BY 10;

/* ---------- Exceptions --------------------------------------------- */

CREATE EXCEPTION E_CUSTOMER_NOT_FOUND 'Customer not found.';
CREATE EXCEPTION E_NEGATIVE_AMOUNT    'Amount must not be negative.';
CREATE EXCEPTION E_ORDER_LOCKED       'Order is locked and cannot be modified.';

/* ---------- Roles -------------------------------------------------- */

CREATE ROLE LAB_READER;
CREATE ROLE LAB_EDITOR;
CREATE ROLE LAB_ADMIN;

/* ---------- Tables --------------------------------------------------
   Cover: PK, FK, composite PK, unique, computed fields, identity
          (BY DEFAULT and ALWAYS), fields using domains.              */

CREATE TABLE CUSTOMERS (
  CUSTOMER_ID INTEGER GENERATED BY DEFAULT AS IDENTITY,
  CODE        D_CODE,
  NAME        D_NAME,
  EMAIL       VARCHAR(120),
  BIRTH_DATE  D_BIRTHDATE,
  IS_ACTIVE   D_FLAG,
  CREATED_AT  D_CREATED,
  CONSTRAINT PK_CUSTOMERS      PRIMARY KEY (CUSTOMER_ID),
  CONSTRAINT UQ_CUSTOMERS_CODE UNIQUE (CODE),
  CONSTRAINT UQ_CUSTOMERS_MAIL UNIQUE (EMAIL)
);

CREATE TABLE PRODUCTS (
  PRODUCT_ID     INTEGER GENERATED ALWAYS AS IDENTITY,
  SKU            D_CODE NOT NULL,
  NAME           D_NAME,
  UNIT_PRICE     D_AMOUNT,
  TAX_RATE       NUMERIC(5,2) DEFAULT 23 NOT NULL,
  PRICE_WITH_TAX COMPUTED BY (UNIT_PRICE * (1 + TAX_RATE / 100)),
  CONSTRAINT PK_PRODUCTS     PRIMARY KEY (PRODUCT_ID),
  CONSTRAINT UQ_PRODUCTS_SKU UNIQUE (SKU)
);

CREATE TABLE ORDERS (
  ORDER_ID     INTEGER NOT NULL,
  CUSTOMER_ID  INTEGER NOT NULL,
  ORDER_DATE   D_CREATED,
  STATUS       D_CODE DEFAULT 'NEW',
  TOTAL_AMOUNT D_AMOUNT,
  CONSTRAINT PK_ORDERS       PRIMARY KEY (ORDER_ID),
  CONSTRAINT FK_ORDERS_CUST  FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS (CUSTOMER_ID)
);

CREATE TABLE ORDER_ITEMS (
  ORDER_ID   INTEGER NOT NULL,
  LINE_NO    INTEGER NOT NULL,
  PRODUCT_ID INTEGER NOT NULL,
  QTY        D_QTY,
  UNIT_PRICE D_AMOUNT,
  LINE_TOTAL COMPUTED BY (QTY * UNIT_PRICE),
  CONSTRAINT PK_ORDER_ITEMS  PRIMARY KEY (ORDER_ID, LINE_NO),
  CONSTRAINT FK_ITEMS_ORDER  FOREIGN KEY (ORDER_ID)   REFERENCES ORDERS (ORDER_ID),
  CONSTRAINT FK_ITEMS_PROD   FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS (PRODUCT_ID)
);

CREATE TABLE AUDIT_LOG (
  LOG_ID    INTEGER GENERATED BY DEFAULT AS IDENTITY,
  ENTITY    VARCHAR(30) NOT NULL,
  ENTITY_ID INTEGER,
  ACTION    VARCHAR(20),
  DETAILS   D_NOTES,
  LOGGED_AT D_CREATED,
  CONSTRAINT PK_AUDIT_LOG PRIMARY KEY (LOG_ID)
);

/* ---------- Standalone indexes --------------------------------------
   Exercise the Index Detail surface: a plain index, a DESCENDING index,
   a composite index, a standalone UNIQUE index, an expression index, and
   one INACTIVE index. (PK / FK / UNIQUE *constraint* backing indexes are
   created implicitly by the table constraints above.)                */

CREATE INDEX IDX_ORDERS_DATE          ON ORDERS (ORDER_DATE);
CREATE DESCENDING INDEX IDX_ORDERS_AMT ON ORDERS (TOTAL_AMOUNT);
CREATE INDEX IDX_ITEMS_PROD_QTY       ON ORDER_ITEMS (PRODUCT_ID, QTY);
CREATE UNIQUE INDEX IDX_CUST_EMAIL_U  ON CUSTOMERS (EMAIL);
CREATE INDEX IDX_CUST_NAME_UPPER      ON CUSTOMERS COMPUTED BY (UPPER(NAME));
CREATE INDEX IDX_ORDERS_STATUS        ON ORDERS (STATUS);
ALTER INDEX IDX_ORDERS_STATUS INACTIVE;
COMMENT ON INDEX IDX_ORDERS_DATE IS 'Lookup orders by date (lab).';

/* ---------- Views ---------------------------------------------------
   Cover: simple, join, aggregate.                                    */

CREATE VIEW V_ACTIVE_CUSTOMERS AS
  SELECT CUSTOMER_ID, CODE, NAME, EMAIL
  FROM CUSTOMERS
  WHERE IS_ACTIVE = 'Y';

CREATE VIEW V_ORDER_DETAILS AS
  SELECT o.ORDER_ID,
         c.NAME       AS CUSTOMER_NAME,
         oi.LINE_NO,
         p.NAME       AS PRODUCT_NAME,
         oi.QTY,
         oi.UNIT_PRICE,
         oi.LINE_TOTAL
  FROM ORDERS o
  JOIN CUSTOMERS   c  ON c.CUSTOMER_ID = o.CUSTOMER_ID
  JOIN ORDER_ITEMS oi ON oi.ORDER_ID   = o.ORDER_ID
  JOIN PRODUCTS    p  ON p.PRODUCT_ID  = oi.PRODUCT_ID;

CREATE VIEW V_CUSTOMER_TOTALS AS
  SELECT c.CUSTOMER_ID,
         c.NAME,
         COUNT(o.ORDER_ID)              AS ORDER_COUNT,
         COALESCE(SUM(o.TOTAL_AMOUNT),0) AS TOTAL_SPENT
  FROM CUSTOMERS c
  LEFT JOIN ORDERS o ON o.CUSTOMER_ID = c.CUSTOMER_ID
  GROUP BY c.CUSTOMER_ID, c.NAME;

/* ---------- Functions (PSQL) ---------------------------------------
   Cover: scalar functions with params, DECLARE, IF/ELSE, RETURN.    */

SET TERM ^ ;

CREATE FUNCTION FN_ADD_TAX(AMOUNT NUMERIC(15,2), RATE NUMERIC(5,2))
RETURNS NUMERIC(15,2)
AS
BEGIN
  RETURN AMOUNT * (1 + RATE / 100);
END^

CREATE FUNCTION FN_FULL_LABEL(CODE VARCHAR(8), NAME VARCHAR(60))
RETURNS VARCHAR(80)
AS
  DECLARE VARIABLE RESULT VARCHAR(80);
BEGIN
  IF (CODE IS NULL) THEN
    RESULT = NAME;
  ELSE
    RESULT = TRIM(CODE) || ' - ' || NAME;
  RETURN RESULT;
END^

SET TERM ; ^

/* ---------- Procedures (PSQL) --------------------------------------
   Cover: input/output params, SUSPEND, CASE, nested BEGIN/END,
          FOR SELECT, exceptions.                                    */

SET TERM ^ ;

CREATE PROCEDURE SP_CUSTOMER_ORDERS(P_CUSTOMER_ID INTEGER)
RETURNS (ORDER_ID INTEGER,
         ORDER_DATE TIMESTAMP,
         STATUS_LABEL VARCHAR(20),
         TOTAL_AMOUNT NUMERIC(15,2))
AS
  DECLARE VARIABLE V_STATUS CHAR(8);
BEGIN
  FOR SELECT o.ORDER_ID, o.ORDER_DATE, o.STATUS, o.TOTAL_AMOUNT
      FROM ORDERS o
      WHERE o.CUSTOMER_ID = :P_CUSTOMER_ID
      INTO :ORDER_ID, :ORDER_DATE, :V_STATUS, :TOTAL_AMOUNT
  DO
  BEGIN
    STATUS_LABEL = CASE TRIM(V_STATUS)
                     WHEN 'NEW'  THEN 'New'
                     WHEN 'PAID' THEN 'Paid'
                     WHEN 'SHIP' THEN 'Shipped'
                     ELSE 'Unknown'
                   END;
    SUSPEND;
  END
END^

CREATE PROCEDURE SP_ADD_ORDER(P_CUSTOMER_ID INTEGER,
                              P_AMOUNT      NUMERIC(15,2))
RETURNS (NEW_ORDER_ID INTEGER)
AS
  DECLARE VARIABLE V_EXISTS INTEGER;
BEGIN
  SELECT COUNT(*) FROM CUSTOMERS
    WHERE CUSTOMER_ID = :P_CUSTOMER_ID
    INTO :V_EXISTS;

  IF (V_EXISTS = 0) THEN
    EXCEPTION E_CUSTOMER_NOT_FOUND;

  IF (P_AMOUNT < 0) THEN
    EXCEPTION E_NEGATIVE_AMOUNT;

  NEW_ORDER_ID = NEXT VALUE FOR GEN_ORDER_ID;
  INSERT INTO ORDERS (ORDER_ID, CUSTOMER_ID, TOTAL_AMOUNT, STATUS)
    VALUES (:NEW_ORDER_ID, :P_CUSTOMER_ID, :P_AMOUNT, 'NEW');
  SUSPEND;
END^

SET TERM ; ^

/* ---------- Triggers (PSQL) ----------------------------------------
   Cover: before insert, before update, after update.                */

SET TERM ^ ;

CREATE TRIGGER TR_ORDERS_BI FOR ORDERS
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
  IF (NEW.ORDER_ID IS NULL) THEN
    NEW.ORDER_ID = NEXT VALUE FOR GEN_ORDER_ID;
  IF (NEW.ORDER_DATE IS NULL) THEN
    NEW.ORDER_DATE = CURRENT_TIMESTAMP;
END^

CREATE TRIGGER TR_ORDERS_BU FOR ORDERS
ACTIVE BEFORE UPDATE POSITION 0
AS
BEGIN
  IF (NEW.TOTAL_AMOUNT < 0) THEN
    EXCEPTION E_NEGATIVE_AMOUNT;
END^

CREATE TRIGGER TR_ORDERS_AU FOR ORDERS
ACTIVE AFTER UPDATE POSITION 0
AS
BEGIN
  IF (OLD.STATUS IS DISTINCT FROM NEW.STATUS) THEN
    INSERT INTO AUDIT_LOG (ENTITY, ENTITY_ID, ACTION, DETAILS)
      VALUES ('ORDERS', NEW.ORDER_ID, 'STATUS_CHANGE',
              'Status changed from ' || TRIM(OLD.STATUS) || ' to ' || TRIM(NEW.STATUS));
END^

SET TERM ; ^

/* ---------- Package + body (PSQL) ----------------------------------
   Cover: package header + body, with a function and a procedure.     */

SET TERM ^ ;

CREATE PACKAGE PKG_ORDERS
AS
BEGIN
  FUNCTION  ORDER_TOTAL(P_ORDER_ID INTEGER) RETURNS NUMERIC(15,2);
  PROCEDURE RECALC_ORDER(P_ORDER_ID INTEGER);
END^

CREATE PACKAGE BODY PKG_ORDERS
AS
BEGIN
  FUNCTION ORDER_TOTAL(P_ORDER_ID INTEGER) RETURNS NUMERIC(15,2)
  AS
    DECLARE VARIABLE V_TOTAL NUMERIC(15,2);
  BEGIN
    SELECT COALESCE(SUM(LINE_TOTAL), 0) FROM ORDER_ITEMS
      WHERE ORDER_ID = :P_ORDER_ID
      INTO :V_TOTAL;
    RETURN V_TOTAL;
  END

  PROCEDURE RECALC_ORDER(P_ORDER_ID INTEGER)
  AS
  BEGIN
    UPDATE ORDERS SET TOTAL_AMOUNT = PKG_ORDERS.ORDER_TOTAL(:P_ORDER_ID)
      WHERE ORDER_ID = :P_ORDER_ID;
  END
END^

SET TERM ; ^

