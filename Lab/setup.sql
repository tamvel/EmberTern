/* ---------- Package + body (PSQL) ----------------------------------
   Cover: package header + body, with a function and a procedure.     */

SET TERM ^ ;

CREATE PACKAGE PKG_ORDERS
AS
BEGIN
  FUNCTION  ORDER_TOTAL(P_ORDER_ID INTEGER) RETURNS NUMERIC(15,2);
  PROCEDURE RECALC_ORDER(P_ORDER_ID INTEGER);
END^

CREATE PACKAGE BODY PKG_ORDERS
AS
BEGIN
  FUNCTION ORDER_TOTAL(P_ORDER_ID INTEGER) RETURNS NUMERIC(15,2)
  AS
    DECLARE VARIABLE V_TOTAL NUMERIC(15,2);
  BEGIN
    SELECT COALESCE(SUM(LINE_TOTAL), 0) FROM ORDER_ITEMS
      WHERE ORDER_ID = :P_ORDER_ID
      INTO :V_TOTAL;
    RETURN V_TOTAL;
  END

  PROCEDURE RECALC_ORDER(P_ORDER_ID INTEGER)
  AS
  BEGIN
    UPDATE ORDERS SET TOTAL_AMOUNT = PKG_ORDERS.ORDER_TOTAL(:P_ORDER_ID)
      WHERE ORDER_ID = :P_ORDER_ID;
  END
END^

